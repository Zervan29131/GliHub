BEGIN
    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'vector') THEN
        IF NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_name = 'ehs_kb_chunk' AND column_name = 'embedding'
        ) THEN
            EXECUTE 'ALTER TABLE ehs_kb_chunk ADD COLUMN embedding vector(1024)';
            EXECUTE 'CREATE INDEX IF NOT EXISTS idx_ehs_kb_chunk_vec ON ehs_kb_chunk USING hnsw (embedding vector_cosine_ops)';
        END IF;
    END IF;
END
$$;

